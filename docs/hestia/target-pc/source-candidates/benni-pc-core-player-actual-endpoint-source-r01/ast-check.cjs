const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const ts = require('C:/IFI_SourceCode/Temp/WeltraumSpiel/artifacts/hestia-target-pc-2026-10-13/rt08-build-toolchain/node_modules/typescript/lib/typescript.js');
const root = path.resolve(__dirname, '../..');
const read = p => ts.createSourceFile(p, fs.readFileSync(p, 'utf8'), ts.ScriptTarget.Latest, true);
const source = read(path.join(root, 'apps/weltraum-browser/src/hestia-prototype/player/locomotion.ts'));
const before = read(path.join(__dirname, 'before/locomotion.ts'));
const tests = read(path.join(root, 'apps/weltraum-browser/tests/unit/hvp-locomotion.test.ts'));
const beforeTests = read(path.join(__dirname, 'before/hvp-locomotion.test.ts'));
for (const f of [source, before, tests, beforeTests]) assert.equal(f.parseDiagnostics.length, 0, f.fileName);
const find = (f, predicate) => { const found = []; const walk = n => { if (predicate(n)) found.push(n); ts.forEachChild(n, walk); }; walk(f); return found; };
const step = f => find(f, n => ts.isMethodDeclaration(n) && n.name.getText(f) === 'step')[0];
const printer = ts.createPrinter();
const print = (n, f) => printer.printNode(ts.EmitHint.Unspecified, n, f);
const statements = [...step(source).body.statements];
const additions = statements.filter(n => /previousGrounded|previousJumpCount/.test(n.getText(source)) ||
  (ts.isExpressionStatement(n) && n.getText(source).startsWith('coverageHold =') && n.getText(source).includes('movement.x')));
assert.equal(additions.length, 3);
assert.deepEqual(statements.filter(n => !additions.includes(n)).map(n => print(n, source)), [...step(before).body.statements].map(n => print(n, before)));
const endpoint = statements.indexOf(additions[1]), hold = statements.indexOf(additions[2]);
assert.equal(hold, endpoint + 1);
assert(statements[endpoint - 1].getText(source).includes('movement.y = rise + profile.offset'));
assert(statements[hold + 1].getText(source).startsWith('grounded = controller.computedGrounded()'));
assert(additions[1].getText(source).includes('position.x + movement.x + x, position.z + movement.z + z'));
assert(additions[2].getText(source).includes('velocityY = 0; jumpPending = false; return;'));
const testCalls = f => find(f, n => ts.isCallExpression(n) && n.expression.getText(f) === 'it');
const existing = testCalls(beforeTests).map(n => print(n, beforeTests));
const after = testCalls(tests);
const added = after.filter(n => !existing.includes(print(n, tests)));
assert.equal(added.length, 1);
assert.equal(after.length, existing.length + 1);
assert.deepEqual(after.filter(n => !added.includes(n)).map(n => print(n, tests)), existing);
assert(added[0].getText(tests).includes('mockReturnValueOnce({ x: 1, y: 0.2, z: 0 })'));
assert(added[0].getText(tests).includes('position: before.position'));
